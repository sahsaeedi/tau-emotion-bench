from typing import Optional

from tau_emotion.data_model.tasks import Task
from tau_emotion.domains.restaurant.data_model import RestaurantDB
from tau_emotion.domains.restaurant.tools import RestaurantTools
from tau_emotion.domains.restaurant.utils import (
    RESTAURANT_DB_PATH,
    RESTAURANT_POLICY_PATH,
    RESTAURANT_TASK_SET_PATH,
    RESTAURANT_TRAIN_DB_PATH,
    RESTAURANT_TRAIN_TASK_SET_PATH,
)
from tau_emotion.domains.task_loading import db_path, load_tasks, task_splits
from tau_emotion.environment.environment import Environment


def get_environment(
    db: Optional[RestaurantDB] = None,
    solo_mode: bool = False,
    db_split: str = "test",
) -> Environment:
    """Build the restaurant environment.

    Args:
        db: Database to use. None loads the one for `db_split`.
        solo_mode: Unsupported in this domain.
        db_split: Which database to load: "test" for the shipped db.json
            (default), "train" for db_train.json, which the training tasks
            reference.
    """
    if solo_mode:
        raise ValueError("Restaurant domain does not support solo mode")
    if db is None:
        db = RestaurantDB.load(
            db_path(
                "restaurant",
                db_split,
                test_path=RESTAURANT_DB_PATH,
                train_path=RESTAURANT_TRAIN_DB_PATH,
            )
        )
    tools = RestaurantTools(db)
    with open(RESTAURANT_POLICY_PATH, "r") as fp:
        policy = fp.read()
    return Environment(
        domain_name="restaurant",
        policy=policy,
        tools=tools,
    )


def get_tasks(
    task_split_name: Optional[str] = "base",
) -> list[Task]:
    """Load restaurant tasks generated by TRACER.

    Args:
        task_split_name:
            - "base"  -> the shipped benchmark tasks. Default.
            - "test"  -> the same tasks, filtered to the test split
            - "train" -> the combined training tasks (tasks_train.json)
            - None    -> same as "base"

    Note:
        The training tasks reference records that exist only in the train
        database, so run them against `get_environment(db_split="train")`.
    """
    return load_tasks(
        "restaurant",
        task_split_name,
        test_path=RESTAURANT_TASK_SET_PATH,
        train_path=RESTAURANT_TRAIN_TASK_SET_PATH,
    )


def get_tasks_split() -> dict[str, list[str]]:
    """Split-name -> task-id mapping, derived from the task files.

    'base' and 'test' are the benchmark set (tasks.json); 'train' is
    tasks_train.json.
    """
    return task_splits(RESTAURANT_TASK_SET_PATH, RESTAURANT_TRAIN_TASK_SET_PATH)
