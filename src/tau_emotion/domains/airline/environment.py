from typing import Optional

from tau_emotion.data_model.tasks import Task
from tau_emotion.domains.airline.data_model import FlightDB
from tau_emotion.domains.airline.tools import AirlineTools
from tau_emotion.domains.airline.utils import (
    AIRLINE_DB_PATH,
    AIRLINE_POLICY_PATH,
    AIRLINE_TASK_SET_PATH,
    AIRLINE_TRAIN_DB_PATH,
    AIRLINE_TRAIN_TASK_SET_PATH,
)
from tau_emotion.domains.task_loading import db_path, load_tasks, task_splits
from tau_emotion.environment.environment import Environment


def get_environment(
    db: Optional[FlightDB] = None,
    solo_mode: bool = False,
    db_split: str = "test",
) -> Environment:
    """Build the airline environment.

    Args:
        db: Database to use. None loads the one for `db_split`.
        solo_mode: Unsupported in this domain.
        db_split: Which database to load: "test" for the shipped db.json
            (default), "train" for db_train.json, which the training tasks
            reference.
    """
    if solo_mode:
        raise ValueError("Airline domain does not support solo mode")
    if db is None:
        db = FlightDB.load(
            db_path(
                "airline",
                db_split,
                test_path=AIRLINE_DB_PATH,
                train_path=AIRLINE_TRAIN_DB_PATH,
            )
        )
    tools = AirlineTools(db)
    with open(AIRLINE_POLICY_PATH, "r") as fp:
        policy = fp.read()
    return Environment(
        domain_name="airline",
        policy=policy,
        tools=tools,
    )


def get_tasks(
    task_split_name: Optional[str] = "base",
) -> list[Task]:
    """Load airline tasks generated by TRACER.

    Args:
        task_split_name:
            - "base"  -> the shipped benchmark tasks. Default.
            - "test"  -> the same tasks, filtered to the test split
            - "train" -> the combined training tasks (tasks_train.json)
            - None    -> same as "base"

    Note:
        The training tasks reference records that exist only in the train
        database, so run them against `get_environment(db_split="train")`.
    """
    return load_tasks(
        "airline",
        task_split_name,
        test_path=AIRLINE_TASK_SET_PATH,
        train_path=AIRLINE_TRAIN_TASK_SET_PATH,
    )


def get_tasks_split() -> dict[str, list[str]]:
    """Split-name -> task-id mapping, derived from the task files.

    'base' and 'test' are the benchmark set (tasks.json); 'train' is
    tasks_train.json.
    """
    return task_splits(AIRLINE_TASK_SET_PATH, AIRLINE_TRAIN_TASK_SET_PATH)
