    @is_tool(ToolType.WRITE)
    def create_booking(
        self,
        theater_id: str,
        show_id: str,
        customer: dict,
        seats: List[dict],
        delivery_method: DeliveryMethod,
        payments: List[dict],
        concessions: Optional[List[dict]] = None,
        special_requests: Optional[str] = None,
    ) -> Booking:
        """
        Create a booking for a show with selected seats and optional concessions.

        The agent needs to explain the details and ask for explicit user
        confirmation (yes/no) before calling.

        Args:
            theater_id: The theater id.
            show_id: The show id.
            customer: Customer info with name ({first_name, last_name}), email,
                phone, and an optional loyalty_id.
            seats: List of seat specs to book, each {seat_id, ticket_type}.
            delivery_method: Delivery method for tickets, one of 'e-ticket',
                'box-office', 'kiosk'.
            payments: Payments whose amounts sum to the grand total from
                price_preview, each {amount, method: {source}} where source is
                one of 'card', 'wallet', 'cash', 'gift_card'. The system
                assigns the booking id, payment ids and timestamps.
            concessions: Optional list of concession specs.
            special_requests: Optional free-text request recorded on the booking.

        Returns:
            The newly created booking.

        Raises:
            ValueError: If the theater, show or auditorium is not found, the
                show is not bookable, a seat is unknown or taken, or the
                payments do not sum to the grand total.
        """
        theater = self._get_theater(theater_id)
        show, date = self._find_show(theater_id, show_id)
        if show.status != "scheduled":
            raise ValueError(
                f"Show {show_id} is not available for booking (status={show.status})"
            )
        self._validate_seats_available(theater, show, seats)

        booked_seats = self._build_booked_seats(show, theater, seats)
        lines = self._concession_lines(theater, concessions or [])
        breakdown = self._price(theater, booked_seats, lines)
        grand_total = breakdown["grand_total"]

        total_paid = round(sum(float(p["amount"]) for p in payments), 2)
        if total_paid != grand_total:
            raise ValueError(
                f"Payment amount does not add up, total price is {grand_total}, "
                f"but paid {total_paid}"
            )

        booking_id = self._new_booking_id()
        booking = Booking(
            booking_id=booking_id,
            theater_id=theater_id,
            movie_id=show.movie_id,
            show_id=show_id,
            date=date,
            start_time_local=show.start_time_local,
            status="confirmed",
            created_at=BOOKING_CREATED_AT,
            canceled_at=None,
            customer=Customer.model_validate(customer),
            seats=booked_seats,
            concessions=lines,
            promotions_applied=[],
            payment_history=self._record_payments(booking_id, payments),
            totals=BookingTotals(
                tickets_subtotal=breakdown["tickets_subtotal"],
                concessions_subtotal=breakdown["concessions_subtotal"],
                fees_total=breakdown["fees_total"],
                tax_total=breakdown["tax_total"],
                grand_total=grand_total,
                amount_paid=total_paid,
                amount_due=round(grand_total - total_paid, 2),
            ),
            delivery=Delivery(
                method=delivery_method,
                tickets=[
                    DeliveryTicket(
                        ticket_id=f"{booking_id}-TKT-{i + 1:03d}",
                        barcode=f"BAR-{booking_id}-TKT-{i + 1:03d}",
                    )
                    for i in range(len(booked_seats))
                ],
            ),
            special_requests=special_requests,
        )

        self.db.bookings[booking_id] = booking
        return booking

    @is_tool(ToolType.WRITE)
    def cancel_booking(self, booking_id: str) -> Booking:
        """
        Cancel a booking and record a refund for the full amount paid.

        Cancelling an already cancelled or refunded booking is a no-op. The
        agent needs to explain the details and ask for explicit user
        confirmation (yes/no) before calling.

        Args:
            booking_id: The booking id.

        Returns:
            The cancelled booking.

        Raises:
            ValueError: If the booking is not found.
        """
        booking = self._get_booking(booking_id)
        if booking.status in ("canceled", "refunded"):
            return booking

        refund_amount = -float(booking.totals.amount_paid)
        if refund_amount != 0.0:
            booking.payment_history.append(
                self._refund_payment(f"{booking_id}-refund", refund_amount)
            )
            booking.totals.amount_paid = round(
                booking.totals.amount_paid + refund_amount, 2
            )
            booking.totals.amount_due = round(
                booking.totals.grand_total - booking.totals.amount_paid, 2
            )

        booking.status = "canceled"
        booking.canceled_at = BOOKING_CREATED_AT
        return booking

    @is_tool(ToolType.WRITE)
    def update_booking_seats(
        self, booking_id: str, seats: List[dict], payment: Optional[dict] = None
    ) -> Booking:
        """
        Change the seats on a confirmed booking, repricing the whole booking.

        Concessions are unchanged. If the new total is higher, a matching
        payment must be supplied; if lower, a refund is recorded. The agent
        needs to explain the details and ask for explicit user confirmation
        (yes/no) before calling.

        Args:
            booking_id: The booking id.
            seats: The complete new list of seat specs, each {seat_id, ticket_type}.
            payment: Additional payment covering a price increase, if there is
                one, as {amount, method: {source}}. The system assigns its id
                and timestamp.

        Returns:
            The updated booking.

        Raises:
            ValueError: If the booking, theater, show or auditorium is not
                found, the booking is not confirmed, the show is not bookable,
                a seat is unknown or taken by someone else, or the supplied
                payment does not match the price increase.
        """
        booking = self._get_booking(booking_id)
        theater = self._get_theater(booking.theater_id)
        show, _ = self._find_show(booking.theater_id, booking.show_id)

        if booking.status != "confirmed":
            raise ValueError(
                f"Only confirmed bookings can be updated (status={booking.status})"
            )
        if show.status != "scheduled":
            raise ValueError(
                f"Show {booking.show_id} is not bookable (status={show.status})"
            )

        current_seat_ids = {s.seat_id for s in booking.seats}
        self._validate_seats_available(
            theater, show, seats, already_held=current_seat_ids
        )

        new_seats = self._build_booked_seats(show, theater, seats)
        breakdown = self._price(theater, new_seats, booking.concessions)
        diff = round(breakdown["grand_total"] - float(booking.totals.grand_total), 2)

        if diff > 0:
            if payment is None or round(float(payment["amount"]), 2) != diff:
                raise ValueError(
                    f"Additional payment of {diff} is required to complete the update"
                )
            n_adj = sum(
                1
                for p in booking.payment_history
                if p.payment_id.startswith(f"{booking_id}-adj-pay-")
            )
            booking.payment_history.append(
                Payment(
                    payment_id=f"{booking_id}-adj-pay-{n_adj + 1:02d}",
                    amount=diff,
                    method=PaymentMethod(source=self._payment_source(payment)),
                    created_at=BOOKING_CREATED_AT,
                )
            )
            booking.totals.amount_paid = round(booking.totals.amount_paid + diff, 2)
        elif diff < 0:
            booking.payment_history.append(
                self._refund_payment(f"{booking_id}-adj-refund", diff)
            )
            booking.totals.amount_paid = round(booking.totals.amount_paid + diff, 2)

        booking.seats = new_seats
        booking.totals.tickets_subtotal = breakdown["tickets_subtotal"]
        booking.totals.fees_total = breakdown["fees_total"]
        booking.totals.tax_total = breakdown["tax_total"]
        booking.totals.grand_total = breakdown["grand_total"]
        booking.totals.amount_due = round(
            booking.totals.grand_total - booking.totals.amount_paid, 2
        )
        return booking

