"""Toolkit for the movie domain, ported from TRACER's environment
(tracer/tracer/envs/movie/).

16 tools: one per tool module in tracer/tracer/envs/movie/tools/.
Conversion rules from TRACER's tools:

- `data["theaters"]` → `self.db.theaters`.
- `return json.dumps(x)` → return the pydantic record.
- `return "Error: ..."` → `raise ValueError("...")`.
- Free-function `invoke(data, ...)` → instance method with `@is_tool(...)`.

TRACER's environment duplicates `_find_show`, `_list_all_seat_ids`,
`_booked_seats_for_show` and the pricing helpers across six tool files, with
`_find_show` returning a 2-tuple in some and a 3-tuple in others. They are single
private methods here.

Booking and payment ids are assigned by the tools in deterministic formats
(`BKG000001`, `<booking>-PAY-01`, `<booking>-adj-pay-01`), so the ground-truth
replay and the agent's run store identical records. TRACER's tool uses random
uuid-based booking ids and takes payment ids from the caller. Refund ids
(`<booking>-refund`, `<booking>-adj-refund`) and the static timestamp match
TRACER's.

Known quirk in TRACER's data, reproduced as-is: the shipped bookings store a
per-seat tax of `price * tax_rate`, but TRACER's own pricing code
(`_build_booked_seats`) computes `(price + convenience_fee) * tax_rate`. The
data was therefore generated by a different formula than the tools use, so
repricing an existing booking — even with an unchanged seat list — can produce a
small difference.
The tool code here follows TRACER's code, not its data.
"""

from __future__ import annotations

from typing import Dict, List, Literal, Optional, Set, Tuple

from tau_emotion.domains.movie.data_model import (
    Auditorium,
    BookedSeat,
    Booking,
    BookingTotals,
    ConcessionLine,
    Customer,
    Delivery,
    DeliveryTicket,
    Movie,
    MovieDB,
    Payment,
    PaymentMethod,
    Show,
    Theater,
)
from tau_emotion.environment.toolkit import ToolKitBase, ToolType, is_tool

TICKET_TYPES = ("adult", "child", "senior")
# Static, as in TRACER's tools, so behaviour stays deterministic across runs.
BOOKING_CREATED_AT = "24-05-15-15-00"


# TRACER declares this as an enum in its tool schemas.
DeliveryMethod = Literal["e-ticket", "box-office", "kiosk"]


class MovieTools(ToolKitBase):
    """All the tools for the movie domain."""

    db: MovieDB

    def __init__(self, db: MovieDB) -> None:
        super().__init__(db)

    # ------------------------------------------------------------------
    # Helpers
    # ------------------------------------------------------------------

    def _get_theater(self, theater_id: str) -> Theater:
        theater = self.db.theaters.get(theater_id)
        if theater is None:
            raise ValueError(f"Theater {theater_id} not found")
        return theater

    def _get_movie(self, movie_id: str) -> Movie:
        movie = self.db.movies.get(movie_id)
        if movie is None:
            raise ValueError(f"Movie {movie_id} not found")
        return movie

    def _get_booking(self, booking_id: str) -> Booking:
        booking = self.db.bookings.get(booking_id)
        if booking is None:
            raise ValueError(f"Booking {booking_id} not found")
        return booking

    def _find_show(
        self, theater_id: str, show_id: str, date: Optional[str] = None
    ) -> Tuple[Show, str]:
        """Find a show in a theater, optionally constrained to one date.

        Returns (show, date_the_show_is_on).

        Raises:
            ValueError: If the theater, date or show is not found.
        """
        theater = self._get_theater(theater_id)
        if date is not None:
            if date not in theater.dates:
                raise ValueError(f"No schedule for date {date} at theater {theater_id}")
            for show in theater.dates[date].shows:
                if show.show_id == show_id:
                    return show, date
            raise ValueError(
                f"Show {show_id} not found on date {date} at theater {theater_id}"
            )
        for day, schedule in theater.dates.items():
            for show in schedule.shows:
                if show.show_id == show_id:
                    return show, day
        raise ValueError(f"Show {show_id} not found at theater {theater_id}")

    def _get_auditorium(self, theater: Theater, show: Show) -> Auditorium:
        auditorium = theater.auditoriums.get(show.auditorium_id)
        if auditorium is None:
            raise ValueError(
                f"Auditorium {show.auditorium_id} not found at "
                f"theater {theater.theater_id}"
            )
        return auditorium

    @staticmethod
    def _all_seat_ids(auditorium: Auditorium) -> Set[str]:
        return {
            seat.seat_id
            for seats in auditorium.seat_map.rows.values()
            for seat in seats
        }

    def _booked_seats_for_show(self, theater_id: str, show_id: str) -> Set[str]:
        """Seats already taken for this show. Only confirmed bookings count."""
        return {
            seat.seat_id
            for booking in self.db.bookings.values()
            if booking.theater_id == theater_id
            and booking.show_id == show_id
            and booking.status == "confirmed"
            for seat in booking.seats
        }

    def _new_booking_id(self) -> str:
        """First free id of the form BKG000001."""
        n = 1
        while f"BKG{n:06d}" in self.db.bookings:
            n += 1
        return f"BKG{n:06d}"

    @staticmethod
    def _payment_source(payment: dict) -> Optional[str]:
        return (payment.get("method") or {}).get("source")

    def _record_payments(self, booking_id: str, payments: List[dict]) -> List[Payment]:
        """Payment ids and timestamps are assigned here; only amount and source
        come from the caller."""
        return [
            Payment(
                payment_id=f"{booking_id}-PAY-{i + 1:02d}",
                amount=round(float(p["amount"]), 2),
                method=PaymentMethod(source=self._payment_source(p)),
                created_at=BOOKING_CREATED_AT,
            )
            for i, p in enumerate(payments)
        ]

    @staticmethod
    def _per_ticket_price(show: Show, ticket_type: str) -> float:
        if ticket_type not in TICKET_TYPES:
            raise ValueError(
                f"Invalid ticket type: {ticket_type}. "
                f"Must be one of {list(TICKET_TYPES)}."
            )
        return float(getattr(show.price_schema, ticket_type))

    def _build_booked_seats(
        self, show: Show, theater: Theater, seat_specs: List[dict]
    ) -> List[BookedSeat]:
        """Price each requested seat, adding the convenience fee and tax."""
        tax_rate = theater.pricing_rules.tax_rate_percent / 100.0
        per_ticket_fee = float(show.price_schema.fees.convenience_fee)

        booked = []
        for spec in seat_specs:
            price = self._per_ticket_price(show, spec["ticket_type"])
            booked.append(
                BookedSeat(
                    seat_id=spec["seat_id"],
                    ticket_type=spec["ticket_type"],
                    price=round(price, 2),
                    convenience_fee=round(per_ticket_fee, 2),
                    tax=round((price + per_ticket_fee) * tax_rate, 2),
                )
            )
        return booked

    @staticmethod
    def _concession_lines(
        theater: Theater, concessions: List[dict]
    ) -> List[ConcessionLine]:
        tax_rate = theater.pricing_rules.tax_rate_percent / 100.0
        lines = []
        for c in concessions:
            quantity = int(c["quantity"])
            price_each = float(c["price_each"])
            tax_each = price_each * tax_rate
            lines.append(
                ConcessionLine(
                    item_id=c["item_id"],
                    name=c["name"],
                    size=c["size"],
                    quantity=quantity,
                    price_each=round(price_each, 2),
                    tax_each=round(tax_each, 2),
                    total=round(quantity * (price_each + tax_each), 2),
                )
            )
        return lines

    @staticmethod
    def _concession_totals(lines: List[ConcessionLine]) -> Tuple[float, float]:
        subtotal = sum(line.price_each * line.quantity for line in lines)
        tax_total = sum(line.tax_each * line.quantity for line in lines)
        return round(subtotal, 2), round(tax_total, 2)

    def _validate_seats_available(
        self,
        theater: Theater,
        show: Show,
        seat_specs: List[dict],
        already_held: Optional[Set[str]] = None,
    ) -> None:
        """Check every requested seat exists in the auditorium and is free.

        `already_held` are seats the caller currently owns, which do not count
        as conflicts when updating an existing booking.
        """
        auditorium = self._get_auditorium(theater, show)
        requested = {s["seat_id"] for s in seat_specs}

        missing = requested - self._all_seat_ids(auditorium)
        if missing:
            raise ValueError(f"Unknown seat ids: {sorted(missing)}")

        taken = self._booked_seats_for_show(theater.theater_id, show.show_id)
        conflict = (requested - (already_held or set())) & taken
        if conflict:
            raise ValueError(f"Seats not available: {sorted(conflict)}")

    def _price(
        self,
        theater: Theater,
        booked_seats: List[BookedSeat],
        concession_lines: List[ConcessionLine],
    ) -> dict:
        """Compute the money breakdown for a set of seats and concessions."""
        tickets_subtotal = round(sum(s.price for s in booked_seats), 2)
        ticket_fees = round(sum(s.convenience_fee for s in booked_seats), 2)
        ticket_tax = round(sum(s.tax for s in booked_seats), 2)
        concessions_subtotal, concessions_tax = self._concession_totals(
            concession_lines
        )
        booking_fee = float(theater.pricing_rules.fees.booking_fee)

        fees_total = round(ticket_fees + booking_fee, 2)
        tax_total = round(ticket_tax + concessions_tax, 2)
        return {
            "tickets_subtotal": tickets_subtotal,
            "concessions_subtotal": concessions_subtotal,
            "fees_total": fees_total,
            "tax_total": tax_total,
            "grand_total": round(
                tickets_subtotal + concessions_subtotal + fees_total + tax_total, 2
            ),
            "booking_fee": round(booking_fee, 2),
        }

    @staticmethod
    def _refund_payment(payment_id: str, amount: float) -> Payment:
        """A refund entry.

        TRACER's tool records these against a placeholder cash method.
        """
        return Payment(
            payment_id=payment_id,
            amount=round(amount, 2),
            method=PaymentMethod(
                source="cash", payment_method_id="refund", extra_info=None
            ),
            created_at=BOOKING_CREATED_AT,
        )

