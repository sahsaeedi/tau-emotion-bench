    @is_tool(ToolType.READ)
    def get_theater_details(self, theater_id: str) -> Theater:
        """
        Get details for a theater, including schedules and auditoriums.

        Args:
            theater_id: The theater id.

        Returns:
            The theater record.

        Raises:
            ValueError: If the theater is not found.
        """
        return self._get_theater(theater_id)

    @is_tool(ToolType.READ)
    def get_movie_details(self, movie_id: str) -> Movie:
        """
        Get details for a movie.

        Args:
            movie_id: The movie id.

        Returns:
            The movie record.

        Raises:
            ValueError: If the movie is not found.
        """
        return self._get_movie(movie_id)

    @is_tool(ToolType.READ)
    def get_booking_details(self, booking_id: str) -> Booking:
        """
        Get booking details.

        Args:
            booking_id: The booking id.

        Returns:
            The booking record.

        Raises:
            ValueError: If the booking is not found.
        """
        return self._get_booking(booking_id)

    @is_tool(ToolType.READ)
    def list_movies(self) -> List[dict]:
        """
        List all movies.

        Returns:
            A list of {movie_id, title}.
        """
        return [
            {"movie_id": m.movie_id, "title": m.title} for m in self.db.movies.values()
        ]

    @is_tool(ToolType.READ)
    def list_theaters(self) -> List[dict]:
        """
        List all theaters.

        Returns:
            A list of {theater_id, name}.
        """
        return [
            {"theater_id": t.theater_id, "name": t.name}
            for t in self.db.theaters.values()
        ]

    @is_tool(ToolType.READ)
    def list_shows(
        self, theater_id: str, date: str, movie_id: Optional[str] = None
    ) -> List[Show]:
        """
        List shows at a given theater for a date, optionally filtered by movie.

        Args:
            theater_id: The theater id.
            date: Date to list shows for, in the format YY-MM-DD, e.g. 24-05-01.
            movie_id: Optional movie id to filter shows by.

        Returns:
            The shows on that date, or an empty list if the theater has no
            schedule for it.

        Raises:
            ValueError: If the theater is not found.
        """
        theater = self._get_theater(theater_id)
        if date not in theater.dates:
            return []
        shows = theater.dates[date].shows
        if movie_id is not None:
            shows = [s for s in shows if s.movie_id == movie_id]
        return shows

    @is_tool(ToolType.READ)
    def get_show_details(
        self, theater_id: str, show_id: str, date: Optional[str] = None
    ) -> Show:
        """
        Get show details.

        Args:
            theater_id: The theater id.
            show_id: The show id.
            date: Optional date to constrain the search, in the format YY-MM-DD.

        Returns:
            The show record.

        Raises:
            ValueError: If the theater, date or show is not found.
        """
        show, _ = self._find_show(theater_id, show_id, date)
        return show

    @is_tool(ToolType.READ)
    def get_show_status(self, theater_id: str, show_id: str) -> str:
        """
        Get the current status of a show.

        Args:
            theater_id: The theater id.
            show_id: The show id.

        Returns:
            The show status, e.g. 'scheduled'.

        Raises:
            ValueError: If the theater or show is not found.
        """
        show, _ = self._find_show(theater_id, show_id)
        return show.status

    @is_tool(ToolType.READ)
    def get_seat_availability(
        self, theater_id: str, show_id: str
    ) -> Dict[str, List[str]]:
        """
        Get seat availability for a show.

        Args:
            theater_id: The theater id.
            show_id: The show id.

        Returns:
            An object with keys 'available' and 'booked', each a sorted list
            of seat ids.

        Raises:
            ValueError: If the theater, show or auditorium is not found.
        """
        theater = self._get_theater(theater_id)
        show, _ = self._find_show(theater_id, show_id)
        auditorium = self._get_auditorium(theater, show)

        booked = self._booked_seats_for_show(theater_id, show_id)
        available = self._all_seat_ids(auditorium) - booked
        return {"available": sorted(available), "booked": sorted(booked)}

    @is_tool(ToolType.READ)
    def price_preview(
        self,
        theater_id: str,
        show_id: str,
        seats: List[dict],
        concessions: Optional[List[dict]] = None,
    ) -> dict:
        """
        Preview the price breakdown for a potential booking. No booking is created.

        Args:
            theater_id: The theater id.
            show_id: The show id.
            seats: List of seat specs to price, each {seat_id, ticket_type},
                where ticket_type is one of 'adult', 'child', 'senior'.
            concessions: Optional list of concession specs, each
                {item_id, name, size, quantity, price_each}.

        Returns:
            The price breakdown: tickets_subtotal, concessions_subtotal,
            fees_total, tax_total, grand_total, ticket_count, booking_fee.

        Raises:
            ValueError: If the theater, show or auditorium is not found, the
                show is not bookable, or a seat is unknown or already taken.
        """
        theater = self._get_theater(theater_id)
        show, _ = self._find_show(theater_id, show_id)
        if show.status != "scheduled":
            raise ValueError(
                f"Show {show_id} is not available for booking (status={show.status})"
            )
        self._validate_seats_available(theater, show, seats)

        booked_seats = self._build_booked_seats(show, theater, seats)
        lines = self._concession_lines(theater, concessions or [])
        breakdown = self._price(theater, booked_seats, lines)
        breakdown["ticket_count"] = len(booked_seats)
        return breakdown

