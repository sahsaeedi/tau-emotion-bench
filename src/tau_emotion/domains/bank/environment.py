from typing import Optional

from tau_emotion.data_model.tasks import Task
from tau_emotion.domains.bank.data_model import BankDB
from tau_emotion.domains.bank.tools import BankTools
from tau_emotion.domains.bank.utils import (
    BANK_DB_PATH,
    BANK_POLICY_PATH,
    BANK_TASK_SET_PATH,
    BANK_TRAIN_DB_PATH,
    BANK_TRAIN_TASK_SET_PATH,
)
from tau_emotion.domains.task_loading import db_path, load_tasks, task_splits
from tau_emotion.environment.environment import Environment


def get_environment(
    db: Optional[BankDB] = None,
    solo_mode: bool = False,
    db_split: str = "test",
) -> Environment:
    """Build the bank environment.

    Args:
        db: Database to use. None loads the one for `db_split`.
        solo_mode: Unsupported in this domain.
        db_split: Which database to load: "test" for the shipped db.json
            (default), "train" for db_train.json, which the training tasks
            reference.
    """
    if solo_mode:
        raise ValueError("Bank domain does not support solo mode")
    if db is None:
        db = BankDB.load(
            db_path(
                "bank",
                db_split,
                test_path=BANK_DB_PATH,
                train_path=BANK_TRAIN_DB_PATH,
            )
        )
    tools = BankTools(db)
    with open(BANK_POLICY_PATH, "r") as fp:
        policy = fp.read()
    return Environment(
        domain_name="bank",
        policy=policy,
        tools=tools,
    )


def get_tasks(
    task_split_name: Optional[str] = "base",
) -> list[Task]:
    """Load bank tasks generated by TRACER.

    Args:
        task_split_name:
            - "base"  -> the shipped benchmark tasks. Default.
            - "test"  -> the same tasks, filtered to the test split
            - "train" -> the combined training tasks (tasks_train.json)
            - None    -> same as "base"

    Note:
        The training tasks reference records that exist only in the train
        database, so run them against `get_environment(db_split="train")`.
    """
    return load_tasks(
        "bank",
        task_split_name,
        test_path=BANK_TASK_SET_PATH,
        train_path=BANK_TRAIN_TASK_SET_PATH,
    )


def get_tasks_split() -> dict[str, list[str]]:
    """Split-name -> task-id mapping, derived from the task files.

    'base' is the shipped benchmark set; 'train' is empty until the training
    tasks are built.
    """
    return task_splits(BANK_TASK_SET_PATH, BANK_TRAIN_TASK_SET_PATH)
